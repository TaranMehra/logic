class Solution {
    /**
     * @param {character[][]} board
     * @return {boolean}
     */
    isValidSudoku(board) {
        let set1 = new Set();
        let set2 = new Set();
        let set3 = new Set();
        let whichRow = 1;
        for(let rows of board){
            console.log("................asdjfopasijfrpoawesrfioiae", whichRow)
            if(whichRow == 4 || whichRow == 7 ){
            console.log("sets : ",set1, set2, set3)

                set1.clear();
                set2.clear();
                set3.clear();
            }
            for(let i=0; i < rows.length; i++){
                
                if(i<3){
                    
                    if(set1.has(rows[i])){
                        console.log("Set1 Out", whichRow , i, rows[i] ,'of : ', set1)
                        return false; 
                    }
                    set1.add(rows[i]);
                    // return  set1.has(rows[i]) ?  false : set1.add(rows[i]) 
                }
                else if(i>=3 && i<6){
                    // console.log(rows[i])
                    if(set2.has(rows[i])){
                        console.log("Set2 Out", whichRow , i, rows[i] ,'of : ', set2)
                       return false; 
                    }
                    set2.add(rows[i]);
                }
                else if(i >= 6){
                    if(set3.has(rows[i])){
                        console.log("Set3 Out", whichRow , i, rows[i] ,'of : ', set3)
                       return false; 
                    }
                    set3.add(rows[i]);
                }
                
            }
            whichRow  =  whichRow + 1;

        }
        return true;
    }
}


